import re

HOMO = str.maketrans({"ሐ":"ሀ","ኀ":"ሀ","ሑ":"ሁ","ኁ":"ሁ","ሒ":"ሂ","ኂ":"ሂ","ሓ":"ሃ","ኃ":"ሃ",
    "ሔ":"ሄ","ኄ":"ሄ","ሕ":"ህ","ኅ":"ህ","ሖ":"ሆ","ኆ":"ሆ","ሠ":"ሰ","ሡ":"ሱ","ሢ":"ሲ","ሣ":"ሳ","ሤ":"ሴ",
    "ሥ":"ስ","ሦ":"ሶ","ዐ":"አ","ዑ":"ኡ","ዒ":"ኢ","ዓ":"ኣ","ዔ":"ኤ","ዕ":"እ","ዖ":"ኦ",
    "ፀ":"ጸ","ፁ":"ጹ","ፂ":"ጺ","ፃ":"ጻ","ፄ":"ጼ","ፅ":"ጽ","ፆ":"ጾ"})

def norm(s):
    """For COMPARING texts: no punctuation, look-alike letters unified, single spaces."""
    s = re.sub(r"[።፣፤፥፦፧፠!?,.:;\"'“”‘’«»()\[\]\-]", " ", str(s)).translate(HOMO)
    return re.sub(r"\s+", " ", s).strip()
